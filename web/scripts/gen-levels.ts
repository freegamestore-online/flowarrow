// Generates src/game/levels.ts. Run from web/: node scripts/gen-levels.ts
//
// Each level is solvable by construction. Arrows are placed one at a time, and an arrow is
// only placed where its path to the edge is free of arrows placed before it. Clearing the
// arrows in reverse placement order therefore never hits a blocker. src/game/levels.test.ts
// re-checks every level with the real solver.

import { writeFileSync } from "node:fs";

type Dir = "U" | "D" | "L" | "R";
const STEP: Record<Dir, [number, number]> = { U: [-1, 0], D: [1, 0], L: [0, -1], R: [0, 1] };
const DIRS: Dir[] = ["U", "D", "L", "R"];

interface Tier {
  name: string;
  count: number;
  /** Inclusive board side range. Sizes climb within a tier and never overlap across tiers. */
  sides: [number, number];
  /** Fraction of cells holding an arrow. */
  density: [number, number];
  /** Minimum arrows already blocked at the start, so the level is not free to clear. */
  minBlocked: number;
}

const TIERS: Tier[] = [
  { name: "tier1", count: 15, sides: [4, 5], density: [0.35, 0.5], minBlocked: 1 },
  { name: "tier2", count: 15, sides: [6, 6], density: [0.4, 0.55], minBlocked: 3 },
  { name: "tier3", count: 15, sides: [7, 8], density: [0.45, 0.6], minBlocked: 5 },
  { name: "tier4", count: 15, sides: [9, 10], density: [0.5, 0.65], minBlocked: 8 },
];

function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** Try to fill a `side` x `side` board with about `target` arrows that are solvable by construction. */
function buildLevel(side: number, target: number, rand: () => number): string[] | null {
  const grid: (Dir | null)[][] = Array.from({ length: side }, () => Array<Dir | null>(side).fill(null));
  let placed = 0;
  for (let attempt = 0; attempt < 4000 && placed < target; attempt++) {
    const r = Math.floor(rand() * side);
    const c = Math.floor(rand() * side);
    if (grid[r]?.[c] !== null) continue;
    const dir = DIRS[Math.floor(rand() * 4)] as Dir;
    if (!rayFree(grid, r, c, dir)) continue;
    grid[r]![c] = dir;
    placed++;
  }
  if (placed < target) return null;
  return grid.map((line) => line.map((d) => d ?? ".").join(""));
}

/** True when no arrow lies on the ray from (r, c) toward the edge in direction `dir`. */
function rayFree(grid: (Dir | null)[][], r: number, c: number, dir: Dir): boolean {
  const [dr, dc] = STEP[dir];
  for (let y = r + dr, x = c + dc; y >= 0 && x >= 0 && y < grid.length && x < grid.length; y += dr, x += dc) {
    if (grid[y]?.[x]) return false;
  }
  return true;
}

/** Arrows that have another arrow somewhere on their ray in the full starting board. */
function blockedAtStart(rows: string[]): number {
  let blocked = 0;
  const side = rows.length;
  const at = (r: number, c: number) => rows[r]?.[c] ?? ".";
  for (let r = 0; r < side; r++) {
    for (let c = 0; c < side; c++) {
      const ch = at(r, c);
      if (ch === ".") continue;
      const [dr, dc] = STEP[ch as Dir];
      let hit = false;
      for (let y = r + dr, x = c + dc; y >= 0 && x >= 0 && y < side && x < side; y += dr, x += dc) {
        if (at(y, x) !== ".") { hit = true; break; }
      }
      if (hit) blocked++;
    }
  }
  return blocked;
}

const seen = new Set<string>();
const levels: string[][] = [];
let seed = 20260516;

for (const tier of TIERS) {
  for (let i = 0; i < tier.count; i++) {
    const rand = mulberry32(seed++);
    // Sizes climb through the tier: the first levels use the low side, the last the high side.
    const span = tier.sides[1] - tier.sides[0];
    const side = tier.sides[0] + Math.round((span * i) / Math.max(1, tier.count - 1));

    let rows: string[] | null = null;
    while (!rows) {
      const density = tier.density[0] + (tier.density[1] - tier.density[0]) * rand();
      const candidate = buildLevel(side, Math.round(side * side * density), rand);
      if (!candidate) continue;
      const key = candidate.join("/");
      if (seen.has(key) || blockedAtStart(candidate) < tier.minBlocked) continue;
      seen.add(key);
      rows = candidate;
    }
    levels.push(rows);
  }
}

const body = levels
  .map((rows, i) => {
    const lines = rows.map((row) => `      "${row}",`).join("\n");
    return `  {\n    id: ${i + 1},\n    rows: [\n${lines}\n    ],\n  },`;
  })
  .join("\n");

const out = `// Generated by web/scripts/gen-levels.ts. Do not edit by hand; regenerate instead.

/** One bundled level. \`rows\` uses the board text format from board.ts (U/D/L/R arrows, \`.\` empty). */
export interface LevelDef {
  id: number;
  rows: readonly string[];
}

export const LEVELS: readonly LevelDef[] = [
${body}
];
`;

writeFileSync(new URL("../src/game/levels.ts", import.meta.url), out);
console.log(`Wrote ${levels.length} levels`);
